import { test, expect, addToCart, checkout, demo, focusInside, login, noOverflow } from './helpers'

test.describe('11 · Teclado, foco e responsividade', () => {
  test('skip link, teclado e erros associados aos campos', async ({ page }) => {
    await page.goto('/')
    const skip = page.getByRole('link', { name: 'Pular para o conteúdo', exact: true })
    await skip.focus()
    await page.keyboard.press('Enter')
    await expect(page.getByRole('main')).toBeFocused()
    await page.goto('/login')
    const email = page.getByLabel('E-mail', { exact: true })
    await email.focus()
    await page.keyboard.type('email-invalido')
    await page.keyboard.press('Tab')
    const password = page.getByLabel('Senha', { exact: true })
    await expect(password).toBeFocused()
    await page.keyboard.type('Senha123!')
    await page.keyboard.press('Tab')
    await expect(page.getByRole('button', { name: 'Mostrar senha', exact: true })).toBeFocused()
    await page.keyboard.press('Space')
    await expect(password).toHaveAttribute('type', 'text')
    await page.keyboard.press('Tab')
    await expect(page.getByRole('button', { name: 'Esqueceu a senha?', exact: true })).toBeFocused()
    await page.keyboard.press('Tab')
    const submit = page.getByRole('button', { name: 'Entrar na conta', exact: true })
    await expect(submit).toBeFocused()
    expect(await submit.evaluate((element) => {
      const style = getComputedStyle(element)
      return (style.outlineStyle !== 'none' && style.outlineWidth !== '0px') || style.boxShadow !== 'none'
    })).toBe(true)
    await page.keyboard.press('Enter')
    await expect(email).toHaveAttribute('aria-invalid', 'true')
    const description = await email.getAttribute('aria-describedby')
    expect(description).toBeTruthy()
    await expect(page.locator(`[id="${description}"]`)).toHaveText('Informe um e-mail válido.')
    await expect(page.getByRole('alert')).toBeFocused()
    await noOverflow(page)
  })

  test('diálogo de carteira prende foco, Escape fecha e restaura ao acionador', async ({ page }) => {
    await checkout(page)
    const trigger = page.getByRole('button', { name: 'Conectar', exact: true })
    await trigger.focus()
    await page.keyboard.press('Enter')
    const dialog = page.getByRole('dialog', { name: 'Conectar carteira', exact: true })
    await expect(dialog).toBeVisible()
    await focusInside(page, dialog)
    await page.keyboard.press('Escape')
    await expect(dialog).toHaveCount(0)
    await expect(trigger).toBeFocused()
    await noOverflow(page)
  })

  test('mobile drawer prende foco e devolve ao menu', async ({ page }, testInfo) => {
    test.skip(testInfo.project.name !== 'mobile', 'Drawer disponível no breakpoint mobile.')
    const trigger = page.getByRole('button', { name: 'Explorar coleções', exact: true })
    await trigger.click()
    const dialog = page.getByRole('dialog', { name: 'Explorar coleções', exact: true })
    await focusInside(page, dialog)
    await page.keyboard.press('Escape')
    await expect(trigger).toBeFocused()
    await noOverflow(page)
  })

  test('tablet 768px e reflow equivalente a zoom de 200% não perdem conteúdo', async ({ page }, testInfo) => {
    test.skip(testInfo.project.name !== 'desktop', 'Uma medição tablet/zoom por execução.')
    await page.setViewportSize({ width: 768, height: 1024 })
    await noOverflow(page)
    await page.goto('/nft/cosmic-001')
    await expect(page.getByRole('button', { name: 'Adicionar ao carrinho', exact: false })).toBeVisible()
    await noOverflow(page)
    await login(page, 'alice', '/profile')
    await expect(page.getByRole('button', { name: 'Salvar perfil', exact: true })).toBeVisible()
    await noOverflow(page)
    await page.goto('/wallets')
    await expect(page.getByRole('button', { name: 'Adicionar carteira', exact: true })).toBeVisible()
    await noOverflow(page)
    // 720 CSS px is the reflow width of the 1440px desktop at 200% browser zoom.
    await page.setViewportSize({ width: 720, height: 500 })
    await page.goto('/')
    await noOverflow(page)
    await addToCart(page)
    await noOverflow(page)
    await page.goto('/cart')
    await expect(page.getByRole('link', { name: 'Ir para pagamento', exact: false })).toBeVisible()
    await noOverflow(page)
    await page.goto('/checkout')
    await expect(page.getByLabel('Nome completo', { exact: true })).toBeVisible()
    await noOverflow(page)
    await page.getByRole('button', { name: 'Conectar', exact: true }).click()
    const dialog = page.getByRole('dialog', { name: 'Conectar carteira', exact: true })
    await expect(dialog.getByRole('button', { name: 'Autorizar conexão simulada', exact: true })).toBeVisible()
    await noOverflow(page)
  })
})

test.describe('12 · Skeletons, falha de rede e recuperação', () => {
  for (const [name, path] of [['catálogo', '/'], ['detalhe', '/nft/cosmic-001'], ['carrinho', '/cart']] as const) {
    test(`${name}: skeleton lento respeita reduced-motion; HTTP 503 recupera por retry`, async ({ page }) => {
      if (path === '/cart') await addToCart(page)
      await demo(page, { scenario: 'slow', latency: 1_500 })
      await page.goto(path)
      const loading = page.getByRole('status', { name: 'Carregando conteúdo', exact: true })
      await expect(loading.first()).toBeVisible()
      const skeleton = loading.first().locator('.skeleton').first()
      await expect(skeleton).toBeVisible()
      expect(await page.evaluate(() => matchMedia('(prefers-reduced-motion: reduce)').matches)).toBe(true)
      expect(await skeleton.evaluate((element) => getComputedStyle(element, '::after').animationName)).toBe('none')
      await expect(loading).toHaveCount(0)
      await demo(page, { scenario: 'http-error' })
      await page.reload()
      const alert = page.getByRole('alert').filter({ has: page.getByRole('heading', { name: 'Não foi possível carregar', exact: true }) })
      await expect(alert).toContainText('temporariamente indisponível')
      await demo(page)
      await alert.getByRole('button', { name: 'Tentar novamente', exact: true }).click()
      await expect(alert).toHaveCount(0)
      if (path === '/') await expect(page.locator('.nft-grid .nft-card')).toHaveCount(9)
      if (path.startsWith('/nft/')) await expect(page.getByRole('group', { name: 'Edição', exact: true })).toBeVisible()
      if (path === '/cart') await expect(page.getByTestId('quote-total')).toHaveText('0.123 ETH')
    })
  }

  test('falha de conexão e acesso proibido apresentam feedback sem falso sucesso', async ({ page }) => {
    await demo(page, { scenario: 'offline' })
    await page.goto('/nft/cosmic-001')
    await expect(page.getByRole('alert')).toContainText('Sem conexão')
    await demo(page)
    await page.getByRole('button', { name: 'Tentar novamente', exact: true }).click()
    await expect(page.getByRole('group', { name: 'Edição', exact: true })).toBeVisible()
    await login(page)
    await demo(page, { scenario: 'forbidden' })
    await page.goto('/profile')
    await expect(page.getByRole('alert')).toContainText('permissão')
    await expect(page.getByRole('button', { name: 'Salvar perfil', exact: true })).toHaveCount(0)
    await demo(page)
    await page.getByRole('button', { name: 'Tentar novamente', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Salvar perfil', exact: true })).toBeVisible()
  })
})
