test.describe('10 · Duplicatas, eventos antigos e reconexão', () => {
  test('resposta REST pendente fora de ordem não substitui confirmação Socket.IO terminal', async ({ page }) => {
    await checkout(page, { scenario: 'pending-order' })
    await review(page)
    const id = await confirm(page)
    await expect(page.getByText('Estado: pendente', { exact: true })).toBeVisible()
    await expect(page.locator('.live-badge')).toHaveText('Ao vivo')
    await demo(page, { scenario: 'pending-order', latency: 1_800 })
    const path = `/api/orders/${id}`
    const started = page.waitForRequest((request) => request.method() === 'GET' && new URL(request.url()).pathname === path)
    const delayed = page.waitForResponse((response) => response.request().method() === 'GET' && new URL(response.url()).pathname === path)
    await page.getByRole('button', { name: 'Atualizar estado', exact: true }).click()
    await started
    // Let MSW capture the pending envelope; its configured latency still holds delivery.
    await page.evaluate(() => new Promise<void>((resolve) => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
    await demo(page, { scenario: 'pending-order', action: 'resolve-order', orderId: id, status: 'confirmed' })
    await receipt(page)
    const response = await delayed
    expect((await response.json()).status).toBe('pending')
    await response.finished()
    await page.evaluate(() => new Promise<void>((resolve) => requestAnimationFrame(() => requestAnimationFrame(() => resolve()))))
    await receipt(page)
    await expect(page.getByText('Estado: pendente', { exact: true })).toHaveCount(0)
    const current = await state(page)
    expect(current.orderCount).toBe(1)
    expect(current.orders[0].status).toBe('confirmed')
  })

  test('NFT não regride após duplicata/evento antigo, e reconexão reconcilia o carrinho', async ({ page }) => {
    await login(page)
    await addToCart(page)
    await page.goto('/cart')
    await expect(page.locator('.live-badge')).toHaveText('Ao vivo')
    await demo(page, { action: 'nft-update', nftId: 'cosmic-001', editionId: 'print', price: '0.2' })
    await expect(page.getByTestId('quote-total')).toHaveText('0.203 ETH')
    await demo(page, { action: 'nft-update', nftId: 'cosmic-001', editionId: 'print', price: '0.3' })
    await expect(page.getByTestId('quote-total')).toHaveText('0.303 ETH')
    const notices = await page.locator('.notice').count()
    await demo(page, { action: 'duplicate-event' })
    await demo(page, { action: 'old-event' })
    await expect(page.getByTestId('quote-total')).toHaveText('0.303 ETH')
    await expect(page.locator('.notice')).toHaveCount(notices)
    await demo(page, { action: 'disconnect' })
    await expect(page.locator('.live-badge')).toHaveText('Reconectando')
    await demo(page, { action: 'nft-update', nftId: 'cosmic-001', editionId: 'print', price: '0.4' })
    await expect(page.getByTestId('quote-total')).toHaveText('0.303 ETH')
    await demo(page, { action: 'reconnect' })
    await expect(page.locator('.live-badge')).toHaveText('Ao vivo')
    await expect(page.getByTestId('quote-total')).toHaveText('0.403 ETH')
    await page.goto('/nft/cosmic-001')
    await page.locator('.edition-picker input[value="print"]').check()
    await expect(page.locator('.detail-price')).toHaveText('0.4 ETH')
  })

  test('pendente resiste a disconnect/refresh e eventos atrasados não revertem estado terminal', async ({ page }) => {
    await checkout(page, { scenario: 'pending-order' })
    await review(page)
    const id = await confirm(page)
    await expect(page.getByText('Estado: pendente', { exact: true })).toBeVisible()
    await demo(page, { scenario: 'pending-order', action: 'disconnect' })
    await expect(page.locator('.live-badge')).toHaveText('Reconectando')
    await page.reload()
    await expect(page.getByText('Estado: pendente', { exact: true })).toBeVisible()
    expect((await state(page)).orderCount).toBe(1)
    await demo(page, { scenario: 'pending-order', action: 'reconnect' })
    await expect(page.locator('.live-badge')).toHaveText('Ao vivo')
    await demo(page, { scenario: 'pending-order', action: 'resolve-order', orderId: id, status: 'confirmed' })
    await receipt(page)
    const total = await page.getByTestId('quote-total').innerText()
    const stock = (await state(page)).nfts.find((nft) => nft.id === 'cosmic-001')!.editions.find((edition) => edition.id === 'print')!.stock
    await demo(page, { action: 'duplicate-event' })
    await demo(page, { action: 'old-event' })
    await demo(page, { action: 'resolve-order', orderId: id, status: 'declined' })
    await receipt(page)
    await page.reload()
    await receipt(page)
    await expect(page.getByTestId('quote-total')).toHaveText(total)
    const final = await state(page)
    expect(final.orderCount).toBe(1)
    expect(final.orders[0].status).toBe('confirmed')
    expect(final.nfts.find((nft) => nft.id === 'cosmic-001')!.editions.find((edition) => edition.id === 'print')!.stock).toBe(stock)
    await logout(page)
    await login(page, 'bruno')
    await page.goto(`/order/${id}`)
    await expect(page.getByRole('alert')).toContainText('outro colecionador')
    await demo(page, { action: 'duplicate-event' })
    await expect(page.getByRole('heading', { name: 'Recibo do pedido', exact: true })).toHaveCount(0)
    await expect(page.getByRole('main')).not.toContainText(credentials.alice)
  })
})

