import { test, expect, addToCart, checkout, confirm, connect, credentials, demo, login, logout, receipt, review, state } from './helpers'

test.describe('06 · Compra completa e recibo imutável', () => {
  test('catálogo → detalhe → carrinho → pagamento → confirmação real', async ({ page }) => {
    await login(page)
    const nft = (await state(page)).nfts.find((item) => item.id === 'cosmic-001')!
    await page.locator('.nft-grid').getByRole('link', { name: `Ver ${nft.name}`, exact: true }).click()
    await page.locator('.edition-picker input[value="print"]').check()
    await page.getByLabel('Quantidade', { exact: true }).fill('2')
    await page.getByRole('button', { name: 'Adicionar ao carrinho', exact: false }).click()
    await expect(page.getByText('Obra adicionada ao carrinho.', { exact: true })).toBeVisible()
    await page.getByRole('link', { name: 'Carrinho, 2 itens', exact: true }).click()
    await expect(page.getByTestId('quote-total')).toHaveText('0.243 ETH')
    await page.getByRole('link', { name: 'Ir para pagamento', exact: false }).click()
    await review(page)
    const reviewedTotal = await page.getByTestId('quote-total').innerText()
    await confirm(page)
    await receipt(page)
    await expect(page.getByTestId('quote-total')).toHaveText(reviewedTotal)
    await expect(page.locator('.receipt')).toContainText(nft.name)
    await expect(page.locator('.receipt')).toContainText('2 unidade(s)')
    await expect(page.locator('.receipt')).toContainText(/0x[0-9a-f]{64}/)
    await page.getByRole('button', { name: 'Ver referência de transação', exact: false }).click()
    await expect(page.getByRole('dialog', { name: 'Explorador simulado', exact: true })).toContainText('não existe em uma blockchain real')
    await page.keyboard.press('Escape')
    await demo(page, { action: 'nft-update', nftId: nft.id, editionId: 'print', price: '9.999', stock: 12 })
    await expect(page.getByTestId('quote-total')).toHaveText(reviewedTotal)
    await page.reload()
    await receipt(page)
    await expect(page.getByTestId('quote-total')).toHaveText(reviewedTotal)
    await expect(page.locator('.receipt')).toContainText('0.12 ETH / unidade')
    await page.goto('/cart')
    await expect(page.getByText('O carrinho está vazio.', { exact: false })).toBeVisible()
    expect((await state(page)).orderCount).toBe(1)
  })

  test('confirmação remove somente as quantidades compradas, preservando adições posteriores', async ({ page }) => {
    await checkout(page, { scenario: 'pending-order', quantity: 2 })
    await review(page)
    const orderId = await confirm(page)
    await expect(page.getByText('Estado: pendente', { exact: true })).toBeVisible()
    await addToCart(page, { quantity: 1 })
    await addToCart(page, { nftId: 'orbit-002' })
    await demo(page, { scenario: 'pending-order', action: 'resolve-order', orderId, status: 'confirmed' })
    await page.goto(`/order/${orderId}`)
    await receipt(page)
    await page.goto('/cart')
    await expect(page.locator('.cart-line')).toHaveCount(2)
    const originalName = (await state(page)).nfts.find((nft) => nft.id === 'cosmic-001')!.name
    await expect(page.getByLabel(`Quantidade de ${originalName}`, { exact: true })).toHaveValue('1')
    expect((await state(page)).orderCount).toBe(1)
  })
})

test.describe('07 · Recusa, clique repetido e timeout', () => {
  test('pagamento recusado não mostra confirmação nem consome carrinho', async ({ page }) => {
    await checkout(page, { scenario: 'payment-declined', quantity: 2 })
    await review(page)
    const id = await confirm(page)
    await expect(page.getByRole('heading', { name: 'Não foi dessa vez', exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Recibo do pedido', exact: true })).toHaveCount(0)
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Não foi dessa vez', exact: true })).toBeVisible()
    await demo(page, { action: 'resolve-order', orderId: id, status: 'confirmed' })
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Não foi dessa vez', exact: true })).toBeVisible()
    await page.getByRole('link', { name: 'Ver meu carrinho', exact: true }).click()
    await expect(page.locator('.cart-line input[type="number"]')).toHaveValue('2')
    await expect(page.getByTestId('quote-total')).toHaveText('0.243 ETH')
    expect((await state(page)).orders[0].status).toBe('declined')
  })

  test('dois cliques de confirmação criam apenas um pedido', async ({ page }) => {
    await checkout(page, { scenario: 'pending-order' })
    await review(page)
    await page.getByRole('button', { name: 'Confirmar pagamento', exact: false }).dblclick({ delay: 20 })
    await expect(page).toHaveURL(/\/order\/[^/?]+/)
    await expect(page.getByText('Estado: pendente', { exact: true })).toBeVisible()
    const current = await state(page)
    expect(current.orderCount).toBe(1)
    await demo(page, { action: 'resolve-order', orderId: current.orders[0].id, status: 'confirmed' })
    await receipt(page)
    await page.reload()
    await receipt(page)
    expect((await state(page)).orderCount).toBe(1)
  })

  test('timeout após criação recupera a mesma chave e pedido mesmo após refresh', async ({ page }) => {
    await checkout(page, { scenario: 'order-timeout' })
    await review(page)
    const attempts: { key: string; body: string | null }[] = []
    page.on('request', (request) => {
      if (request.method() === 'POST' && new URL(request.url()).pathname === '/api/orders') {
        attempts.push({ key: request.headers()['idempotency-key'], body: request.postData() })
      }
    })
    await page.getByRole('button', { name: 'Confirmar pagamento', exact: false }).click()
    await expect(page.getByRole('alert').filter({ hasText: 'A resposta demorou' })).toBeVisible({ timeout: 15_000 })
    await expect(page.getByRole('heading', { name: 'Tentativa preservada', exact: true })).toBeVisible()
    const before = await state(page)
    expect(before.orderCount).toBe(1)
    await page.reload()
    await expect(page.getByRole('heading', { name: 'Tentativa preservada', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Recuperar tentativa', exact: false }).click()
    await expect(page).toHaveURL(new RegExp(`/order/${before.orders[0].id}$`))
    await receipt(page)
    expect((await state(page)).orderCount).toBe(1)
    expect(attempts).toHaveLength(2)
    expect(attempts[0].key).toBeTruthy()
    expect(attempts[1]).toEqual(attempts[0])
  })

  test('visitar recibo antigo não apaga a tentativa com timeout de uma nova compra', async ({ page }) => {
    await checkout(page)
    await review(page)
    const oldId = await confirm(page)
    await receipt(page)
    await addToCart(page)
    await demo(page, { scenario: 'order-timeout' })
    await page.goto('/checkout')
    await expect(page.getByRole('heading', { name: 'Dados do colecionador', exact: true })).toBeVisible()
    await review(page)
    await page.getByRole('button', { name: 'Confirmar pagamento', exact: false }).click()
    await expect(page.getByRole('alert').filter({ hasText: 'A resposta demorou' })).toBeVisible({ timeout: 15_000 })
    const attempt = await page.evaluate(() => localStorage.getItem('orbit:attempt:alice'))
    expect(attempt).toBeTruthy()
    const current = await state(page)
    expect(current.orderCount).toBe(2)
    const nextId = current.orders.find((order) => order.id !== oldId)!.id
    await page.goto(`/order/${oldId}`)
    await receipt(page)
    expect(await page.evaluate(() => localStorage.getItem('orbit:attempt:alice'))).toBe(attempt)
    await page.goto('/checkout')
    await expect(page.getByRole('heading', { name: 'Tentativa preservada', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'Recuperar tentativa', exact: false }).click()
    await expect(page).toHaveURL(new RegExp(`/order/${nextId}$`))
    await receipt(page)
    await expect.poll(() => page.evaluate(() => localStorage.getItem('orbit:attempt:alice'))).toBeNull()
    expect((await state(page)).orderCount).toBe(2)
  })
})

