import { test, expect, demo, noOverflow, state } from './helpers'

test.describe('01 · Descoberta e URL', () => {
  test('busca, filtros combinados, ordenação, paginação, refresh e histórico', async ({ page }) => {
    await page.getByRole('button', { name: 'Próxima página', exact: true }).click()
    await expect(page).toHaveURL(/[?&]page=2(?:&|$)/)
    await expect(page.locator('.nft-grid .nft-card')).toHaveCount(9)
    const secondPage = await page.locator('.nft-grid h3').allTextContents()
    await page.reload()
    await expect(page.locator('.nft-grid h3')).toHaveText(secondPage)

    const filterButton = page.getByRole('button', { name: 'Filtros', exact: true })
    const mobileFilters = await filterButton.isVisible()
    if (mobileFilters) await filterButton.click()
    const filters = mobileFilters ? page.getByRole('dialog', { name: 'Filtrar obras', exact: true }) : page.locator('.catalog-filters')
    await filters.getByLabel('Categoria', { exact: true }).selectOption('Arte')
    await expect(page).toHaveURL(/[?&]page=1(?:&|$)/)
    await filters.getByLabel('Mín. ETH', { exact: true }).fill('0.5')
    await filters.getByLabel('Mín. ETH', { exact: true }).press('Enter')
    await filters.getByLabel('Máx. ETH', { exact: true }).fill('3.5')
    await filters.getByLabel('Máx. ETH', { exact: true }).press('Tab')
    await filters.getByLabel('Somente disponíveis', { exact: true }).check()
    if (mobileFilters) {
      await page.getByRole('button', { name: 'Ver resultados', exact: true }).click()
    }
    await page.getByRole('combobox', { name: 'Ordenar NFTs', exact: true }).selectOption('name')
    await page.getByRole('textbox', { name: 'Buscar NFTs', exact: true }).fill('Luna')
    await expect(page).toHaveURL(/[?&]q=Luna(?:&|$)/)
    await expect(page).toHaveURL(/[?&]category=Arte(?:&|$)/)
    await expect(page).toHaveURL(/[?&]sort=name(?:&|$)/)
    const matching = (await state(page)).nfts.filter((nft) =>
      nft.category === 'Arte' && nft.creator.includes('Luna') && nft.editions.some((edition) => edition.stock > 0),
    ).filter((nft) => {
      const price = Number(nft.editions[0].price)
      return price >= 0.5 && price <= 3.5
    }).sort((a, b) => a.name.localeCompare(b.name)).map((nft) => nft.name)
    await expect(page.locator('.nft-grid h3')).toHaveText(matching)
    const filteredURL = page.url()
    await page.reload()
    await expect(page.locator('.nft-grid h3')).toHaveText(matching)
    await page.getByRole('textbox', { name: 'Buscar NFTs', exact: true }).fill('nenhum-resultado-orbit')
    await expect(page.getByRole('heading', { name: 'Nenhuma obra por aqui', exact: true })).toBeVisible()
    await page.goBack()
    await expect(page).toHaveURL(filteredURL)
    await expect(page.locator('.nft-grid h3')).toHaveText(matching)
    await page.goForward()
    await expect(page.getByRole('heading', { name: 'Nenhuma obra por aqui', exact: true })).toBeVisible()
  })

  test('decimais completos aplicam por Enter/blur, rejeitam excesso de precisão e ordenam por preço', async ({ page }) => {
    const trigger = page.getByRole('button', { name: 'Filtros', exact: true })
    const mobileFilters = await trigger.isVisible()
    if (mobileFilters) await trigger.click()
    const filters = mobileFilters ? page.getByRole('dialog', { name: 'Filtrar obras', exact: true }) : page.locator('.catalog-filters')
    const min = filters.getByLabel('Mín. ETH', { exact: true })
    const max = filters.getByLabel('Máx. ETH', { exact: true })
    await min.fill('0.')
    await expect(min).toHaveValue('0.')
    await min.pressSequentially('5')
    await expect(min).toHaveValue('0.5')
    await min.press('Enter')
    await max.fill('1.1234567890123456789')
    await max.press('Enter')
    await expect(max).toHaveAttribute('aria-invalid', 'true')
    await expect(filters.getByText('Use um decimal com até 18 casas.', { exact: true })).toBeVisible()
    await max.fill('3.5')
    await max.press('Tab')
    await expect(max).toHaveAttribute('aria-invalid', 'false')
    if (mobileFilters) await filters.getByRole('button', { name: 'Ver resultados', exact: true }).click()
    const nfts = (await state(page)).nfts.filter((nft) => Number(nft.editions[0].price) >= 0.5 && Number(nft.editions[0].price) <= 3.5)
    const ascending = [...nfts].sort((a, b) => Number(a.editions[0].price) - Number(b.editions[0].price)).map((nft) => nft.name)
    await page.getByRole('combobox', { name: 'Ordenar NFTs', exact: true }).selectOption('price-asc')
    await expect(page.locator('.nft-grid h3')).toHaveText(ascending.slice(0, 9))
    await page.getByRole('combobox', { name: 'Ordenar NFTs', exact: true }).selectOption('price-desc')
    await expect(page.locator('.nft-grid h3')).toHaveText(ascending.reverse().slice(0, 9))
  })

  test('descarta respostas antigas sem sobrescrever a última busca', async ({ page }) => {
    await demo(page, { scenario: 'out-of-order' })
    const oldRequest = page.waitForRequest((request) => new URL(request.url()).pathname === '/api/nfts' && new URL(request.url()).searchParams.get('q') === 'Luna')
    await page.getByRole('textbox', { name: 'Buscar NFTs', exact: true }).fill('Luna')
    await oldRequest
    await page.getByRole('textbox', { name: 'Buscar NFTs', exact: true }).fill('Maya')
    const expected = (await state(page)).nfts.filter((nft) => nft.creator === 'Maya Chen').map((nft) => nft.name)
    await expect(page.locator('.nft-grid h3')).toHaveText(expected)
    // The old MSW envelope takes at most 1.5s; assert again after its delivery window.
    await page.waitForTimeout(1_600)
    await expect(page.locator('.nft-grid h3')).toHaveText(expected)
    await expect(page).toHaveURL(/[?&]q=Maya(?:&|$)/)
  })
})

test.describe('02 · Detalhe e rotas diretas', () => {
  test('galeria, edição, estoque e limites inteiros', async ({ page }) => {
    const nft = (await state(page)).nfts.find((item) => item.id === 'cosmic-001')!
    await page.goto(`/nft/${nft.id}`)
    await expect(page.getByRole('heading', { level: 1 })).toHaveText(nft.name)
    const art = page.getByRole('region', { name: 'Galeria da obra', exact: true }).locator('.detail-image img')
    const original = await art.getAttribute('src')
    await page.getByRole('button', { name: 'Ampliar arte', exact: true }).click()
    const zoom = page.getByRole('dialog', { name: nft.name, exact: true })
    await expect(zoom.getByRole('img', { name: `Arte ampliada ${nft.name}`, exact: true })).toHaveAttribute('src', original!)
    await page.keyboard.press('Escape')
    await expect(zoom).toHaveCount(0)
    const quantity = page.getByLabel('Quantidade', { exact: true })
    const add = page.getByRole('button', { name: 'Adicionar ao carrinho', exact: false })
    await quantity.fill('2')
    await expect(add).toBeDisabled()
    await quantity.fill('0')
    await expect(add).toBeDisabled()
    await quantity.fill('1.5')
    await expect(add).toBeDisabled()
    await page.locator('.edition-picker input[value="print"]').check()
    await expect(quantity).toHaveValue('1')
    await expect(add).toBeEnabled()
    await expect(page.locator('.live-badge')).toHaveText('Ao vivo')
    await demo(page, { action: 'nft-update', nftId: nft.id, editionId: 'print', stock: 25 })
    await expect(quantity).toHaveAttribute('max', '10')
    await quantity.fill('11')
    await expect(add).toBeDisabled()
    await quantity.fill('10')
    await expect(add).toBeEnabled()
    await demo(page, { action: 'nft-update', nftId: nft.id, editionId: 'print', stock: 0 })
    await expect(page.getByText('Esta edição está esgotada. Selecione outra edição.', { exact: true })).toBeVisible()
    await expect(add).toBeDisabled()
    await noOverflow(page)
  })

  test('NFT inexistente e rota desconhecida têm recuperação honesta', async ({ page }) => {
    await page.goto('/nft/nao-existe')
    await expect(page.getByRole('alert')).toContainText('NFT não encontrado')
    await page.getByRole('link', { name: 'Voltar ao catálogo', exact: true }).click()
    await expect(page.locator('.nft-grid .nft-card').first()).toBeVisible()
    await page.goto('/rota-que-nao-existe')
    await expect(page.getByRole('heading', { name: 'Página não encontrada', exact: true })).toBeVisible()
    await page.getByRole('link', { name: 'Explorar o catálogo', exact: true }).click()
    await expect(page.locator('.nft-grid .nft-card').first()).toBeVisible()
  })
})
