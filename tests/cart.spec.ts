import { test, expect, addToCart, credentials, state } from './helpers'

test.describe('05 · Carrinho e cotação', () => {
  test('quantidades, cupons, totais exatos, refresh e migração do visitante no login', async ({ page }) => {
    await addToCart(page, { quantity: 2 })
    await page.goto('/cart')
    const nft = (await state(page)).nfts.find((item) => item.id === 'cosmic-001')!
    const quantity = page.getByLabel(`Quantidade de ${nft.name}`, { exact: true })
    await expect(quantity).toHaveValue('2')
    await expect(page.getByTestId('quote-total')).toHaveText('0.243 ETH')
    await quantity.fill('0')
    await quantity.press('Tab')
    await expect(quantity).toHaveAttribute('aria-invalid', 'true')
    await quantity.fill('3')
    await quantity.press('Enter')
    await expect(page.getByTestId('quote-total')).toHaveText('0.363 ETH')
    await page.getByLabel('Cupom de desconto', { exact: true }).fill('INVALIDO')
    await page.getByRole('button', { name: 'Aplicar cupom', exact: true }).click()
    await expect(page.getByLabel('Cupom de desconto', { exact: true })).toHaveAttribute('aria-invalid', 'true')
    await expect(page.getByText('Cupom inválido.', { exact: true }).first()).toBeVisible()
    await page.getByLabel('Cupom de desconto', { exact: true }).fill('EXPIRED')
    await page.getByRole('button', { name: 'Aplicar cupom', exact: true }).click()
    await expect(page.getByText('O cupom expirou.', { exact: true }).first()).toBeVisible()
    await page.getByLabel('Cupom de desconto', { exact: true }).fill('ORBIT10')
    await page.getByRole('button', { name: 'Aplicar cupom', exact: true }).click()
    await expect(page.getByTestId('quote-total')).toHaveText('0.327 ETH')
    await expect(page.getByRole('complementary', { name: 'Resumo de valores', exact: true })).toContainText('0.036 ETH')
    await page.reload()
    await expect(quantity).toHaveValue('3')
    await expect(page.getByTestId('quote-total')).toHaveText('0.327 ETH')
    await page.getByRole('link', { name: 'Ir para pagamento', exact: false }).click()
    await expect(page).toHaveURL(/\/login\?returnTo=%2Fcheckout/)
    await page.getByLabel('E-mail', { exact: true }).fill(credentials.alice)
    await page.getByLabel('Senha', { exact: true }).fill(credentials.password)
    await page.getByRole('button', { name: 'Entrar na conta', exact: true }).click()
    await expect(page).toHaveURL(/\/checkout$/)
    await expect(page.getByTestId('quote-total')).toHaveText('0.327 ETH')
    await page.goto('/cart')
    await page.getByRole('button', { name: 'Remover cupom', exact: true }).click()
    await expect(page.getByTestId('quote-total')).toHaveText('0.363 ETH')
    await page.getByRole('button', { name: `Remover ${nft.name} do carrinho`, exact: true }).click()
    await expect(page.getByText('O carrinho está vazio.', { exact: false })).toBeVisible()
    await page.reload()
    await expect(page.locator('.cart-line')).toHaveCount(0)
  })
})
