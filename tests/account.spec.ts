import { test, expect, credentials, demo, focusInside, login, logout, noOverflow } from './helpers'

const avatarPng = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aN1sAAAAASUVORK5CYII=', 'base64')

function pngWithSize(bytes: number) {
  // A valid PNG ancillary text chunk exercises the exact byte limit without changing the image.
  const dataLength = bytes - avatarPng.length - 12
  const chunk = Buffer.alloc(dataLength + 12, 65)
  chunk.writeUInt32BE(dataLength)
  chunk.write('tEXt', 4, 'ascii')
  chunk.write('Orbit\0', 8, 'ascii')
  let crc = 0xffffffff
  for (const byte of chunk.subarray(4, 8 + dataLength)) {
    crc ^= byte
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ ((crc & 1) ? 0xedb88320 : 0)
  }
  chunk.writeUInt32BE((crc ^ 0xffffffff) >>> 0, chunk.length - 4)
  return Buffer.concat([avatarPng.subarray(0, -12), chunk, avatarPng.subarray(-12)])
}

test.describe('08 · Perfil, avatar, senha e carteiras', () => {
  test('perfil valida conflito e erro da API; upload PNG persiste no refresh', async ({ page }) => {
    await login(page, 'alice', '/profile')
    const favoritesTrigger = page.locator('.account-sidebar').getByRole('button', { name: 'Lista de interesse', exact: true })
    await favoritesTrigger.click()
    const favorites = page.getByRole('dialog', { name: 'Lista de interesse', exact: true })
    await expect(favorites).toContainText('Sua lista está vazia.')
    await focusInside(page, favorites)
    await page.keyboard.press('Escape')
    await expect(favorites).toHaveCount(0)
    await expect(favoritesTrigger).toBeFocused()
    await page.getByLabel('Nome de exibição', { exact: true }).fill('A')
    await page.getByRole('button', { name: 'Salvar perfil', exact: true }).click()
    await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveAttribute('aria-invalid', 'true')
    await page.getByLabel('Nome de exibição', { exact: true }).fill('Alice E2E')
    await page.getByLabel('E-mail', { exact: true }).fill(credentials.bruno)
    await page.getByRole('button', { name: 'Salvar perfil', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('já está cadastrado')
    await page.getByLabel('E-mail', { exact: true }).fill(credentials.alice)
    await demo(page, { scenario: 'validation' })
    await page.getByRole('button', { name: 'Salvar perfil', exact: true }).click()
    await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveAttribute('aria-invalid', 'true')
    await expect(page.getByRole('alert')).toContainText('campos destacados')
    await demo(page)
    await page.getByLabel('E-mail', { exact: true }).fill('alice-edited@orbit.test')
    const upload = page.getByLabel('Avatar', { exact: true })
    await upload.setInputFiles({ name: 'arquivo.txt', mimeType: 'text/plain', buffer: Buffer.from('não é imagem') })
    await expect(upload).toHaveAttribute('aria-invalid', 'true')
    await upload.setInputFiles({ name: 'grande.png', mimeType: 'image/png', buffer: Buffer.alloc(300 * 1024 + 1) })
    await expect(page.getByText('A imagem deve ter conteúdo e no máximo 300 KB.', { exact: true })).toBeVisible()
    // A real, locally supplied 1x1 PNG. SVG is intentionally not accepted by the uploader.
    await upload.setInputFiles({ name: 'avatar.png', mimeType: 'image/png', buffer: avatarPng })
    const preview = page.locator('.account-avatar-large img')
    await expect(preview).toHaveAttribute('src', /^data:image\/png;base64,/)
    await page.getByLabel('Bio', { exact: true }).fill('Coleção persistente E2E')
    await page.getByRole('button', { name: 'Salvar perfil', exact: true }).click()
    await expect(page.getByText('Seu perfil foi atualizado.', { exact: true })).toBeVisible()
    await page.reload()
    await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveValue('Alice E2E')
    await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue('alice-edited@orbit.test')
    await expect(page.getByLabel('Bio', { exact: true })).toHaveValue('Coleção persistente E2E')
    await expect(preview).toHaveAttribute('src', /^data:image\/png;base64,/)
    expect(await preview.evaluate((image) => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
    await noOverflow(page)
  })

  test('avatar aceita PNG válido de exatamente 300KiB na UI e na API', async ({ page }) => {
    await login(page, 'alice', '/profile')
    const png = pngWithSize(300 * 1024)
    expect(png.length).toBe(307_200)
    const expected = `data:image/png;base64,${png.toString('base64')}`
    await page.getByLabel('Avatar', { exact: true }).setInputFiles({ name: 'limite.png', mimeType: 'image/png', buffer: png })
    const preview = page.locator('.account-avatar-large img')
    await expect(preview).toHaveAttribute('src', expected)
    await page.getByRole('button', { name: 'Salvar perfil', exact: true }).click()
    await expect(page.getByText('Seu perfil foi atualizado.', { exact: true })).toBeVisible()
    await page.reload()
    await expect(preview).toHaveAttribute('src', expected)
    expect(await preview.evaluate((image) => (image as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  })

  test('senha valida confirmação e senha atual; nova credencial funciona sem texto puro no storage', async ({ page }) => {
    await login(page, 'alice', '/profile')
    await page.getByLabel('Senha atual', { exact: true }).fill('Errada123!')
    await page.getByLabel('Nova senha', { exact: true }).fill('NovaOrbit456!')
    await page.getByLabel('Confirmar nova senha', { exact: true }).fill('Diferente789!')
    await page.getByRole('button', { name: 'Salvar senha', exact: true }).click()
    await expect(page.getByLabel('Confirmar nova senha', { exact: true })).toHaveAttribute('aria-invalid', 'true')
    await page.getByLabel('Confirmar nova senha', { exact: true }).fill('NovaOrbit456!')
    await page.getByRole('button', { name: 'Salvar senha', exact: true }).click()
    await expect(page.getByLabel('Senha atual', { exact: true })).toHaveAttribute('aria-invalid', 'true')
    await expect(page.getByRole('alert')).toContainText('senha atual está incorreta')
    await page.getByLabel('Senha atual', { exact: true }).fill(credentials.password)
    await page.getByRole('button', { name: 'Salvar senha', exact: true }).click()
    await expect(page.getByText('Senha alterada. Use a nova senha no seu próximo acesso.', { exact: true })).toBeVisible()
    await expect(page.getByLabel('Nova senha', { exact: true })).toHaveValue('')
    await page.reload()
    await logout(page)
    await page.goto('/login?returnTo=%2Fprofile')
    await page.getByLabel('E-mail', { exact: true }).fill(credentials.alice)
    await page.getByLabel('Senha', { exact: true }).fill(credentials.password)
    await page.getByRole('button', { name: 'Entrar na conta', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('incorretos')
    await page.getByLabel('Senha', { exact: true }).fill('NovaOrbit456!')
    await page.getByRole('button', { name: 'Entrar na conta', exact: true }).click()
    await expect(page).toHaveURL(/\/profile$/)
    const storage = await page.evaluate(() => JSON.stringify({ ...localStorage }))
    for (const password of [credentials.password, 'NovaOrbit456!', 'Errada123!']) expect(storage).not.toContain(password)
  })

  test('carteiras validam endereço e conflito; cadastram, editam e trocam principal', async ({ page }) => {
    await login(page, 'alice', '/wallets')
    const trigger = page.getByRole('button', { name: 'Adicionar carteira', exact: true })
    await trigger.click()
    const dialog = page.getByRole('dialog', { name: 'Adicionar carteira', exact: true })
    await focusInside(page, dialog)
    await dialog.getByLabel('Nome da carteira', { exact: true }).fill('Carteira E2E')
    await dialog.getByLabel('Endereço público', { exact: true }).fill('0xinvalido')
    await dialog.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
    await expect(dialog.getByLabel('Endereço público', { exact: true })).toHaveAttribute('aria-invalid', 'true')
    await dialog.getByLabel('Endereço público', { exact: true }).fill(`0x${'a1'.repeat(20)}`)
    await dialog.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
    await expect(dialog.getByRole('alert')).toContainText('já está cadastrada')
    await dialog.getByLabel('Endereço público', { exact: true }).fill(`0x${'c3'.repeat(20)}`)
    await demo(page, { scenario: 'validation' })
    await dialog.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
    await expect(dialog.getByRole('alert')).toContainText('campos destacados')
    await demo(page)
    await dialog.getByLabel('Rede', { exact: true }).selectOption('Polygon')
    await dialog.getByLabel('Carteira principal', { exact: true }).check()
    await dialog.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(trigger).toBeFocused()
    let card = page.locator('.account-wallet-card').filter({ has: page.getByRole('heading', { name: 'Carteira E2E', exact: true }) })
    await expect(card).toContainText('Principal')
    await expect(page.locator('.account-primary-chip')).toHaveCount(1)
    await card.getByRole('button', { name: 'Editar carteira Carteira E2E', exact: true }).click()
    const editor = page.getByRole('dialog', { name: 'Editar carteira', exact: true })
    await editor.getByLabel('Nome da carteira', { exact: true }).fill('Carteira E2E editada')
    await editor.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
    await expect(editor).toHaveCount(0)
    await page.reload()
    card = page.locator('.account-wallet-card').filter({ has: page.getByRole('heading', { name: 'Carteira E2E editada', exact: true }) })
    await expect(card.getByLabel('Endereço público', { exact: true })).toHaveValue(`0x${'c3'.repeat(20)}`)
    await expect(card.getByLabel('Rede', { exact: true })).toHaveValue('Polygon')
    await expect(card).toContainText('Principal')
    await expect(card.getByLabel('Carteira principal', { exact: true })).toBeChecked()
    await expect(page.locator('.account-wallet-inline input[name="primary"]:checked')).toHaveCount(1)
    await expect(page.locator('.account-wallet-card')).toHaveCount(3)
    await noOverflow(page)
  })
})
