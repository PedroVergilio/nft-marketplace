import { test, expect, addToCart, credentials, demo, login, logout, state } from './helpers'

test.describe('03 · Autenticação e isolamento', () => {
  test('cadastro valida campos e conflito; cria conta e recupera sessão no refresh', async ({ page }) => {
    await page.goto('/register?returnTo=%2Fprofile')
    await page.getByRole('button', { name: /^Criar (conta|perfil)$/ }).click()
    await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveAttribute('aria-invalid', 'true')
    await expect(page.getByLabel('E-mail', { exact: true })).toHaveAttribute('aria-invalid', 'true')
    await page.getByLabel('Nome de exibição', { exact: true }).fill('Colecionadora E2E')
    await page.getByLabel('E-mail', { exact: true }).fill(credentials.alice)
    await page.getByLabel('Senha', { exact: true }).fill(credentials.password)
    await page.getByLabel('Confirmar senha', { exact: true }).fill('Diferente123!')
    await page.getByRole('button', { name: /^Criar (conta|perfil)$/ }).click()
    await expect(page.getByLabel('Confirmar senha', { exact: true })).toHaveAttribute('aria-invalid', 'true')
    await page.getByLabel('Confirmar senha', { exact: true }).fill(credentials.password)
    await page.getByRole('button', { name: /^Criar (conta|perfil)$/ }).click()
    await expect(page.getByRole('alert')).toContainText('já está cadastrado')
    await page.getByLabel('E-mail', { exact: true }).fill('colecionadora-e2e@orbit.test')
    await page.getByRole('button', { name: /^Criar (conta|perfil)$/ }).click()
    await expect(page).toHaveURL(/\/profile$/)
    await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveValue('Colecionadora E2E')
    await page.reload()
    await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue('colecionadora-e2e@orbit.test')
    const storage = await page.evaluate(() => JSON.stringify({ ...localStorage }))
    expect(storage).not.toContain(credentials.password)
  })

  test('login inválido, proteção de rota, expiração e retorno ao contexto', async ({ page }) => {
    await page.goto('/wallets')
    await expect(page).toHaveURL(/\/login\?returnTo=%2Fwallets/)
    await page.getByLabel('E-mail', { exact: true }).fill(credentials.alice)
    await page.getByLabel('Senha', { exact: true }).fill('SenhaErrada123!')
    await page.getByRole('button', { name: 'Entrar na conta', exact: true }).click()
    await expect(page.getByRole('alert')).toContainText('incorretos')
    await page.getByLabel('Senha', { exact: true }).fill(credentials.password)
    await page.getByRole('button', { name: 'Entrar na conta', exact: true }).click()
    await expect(page).toHaveURL(/\/wallets$/)
    await expect(page.getByRole('heading', { name: 'Minha Ethereum', exact: true })).toBeVisible()
    await demo(page, { action: 'expire-session' })
    await page.reload()
    await expect(page).toHaveURL(/\/login\?returnTo=%2Fwallets/)
    await page.getByLabel('E-mail', { exact: true }).fill(credentials.alice)
    await page.getByLabel('Senha', { exact: true }).fill(credentials.password)
    await page.getByRole('button', { name: 'Entrar na conta', exact: true }).click()
    await expect(page).toHaveURL(/\/wallets$/)
    await expect(page.getByRole('heading', { name: 'Minha Ethereum', exact: true })).toBeVisible()
  })

  test('logout e troca de usuário não vazam carrinho, perfil, favoritos ou carteiras', async ({ page }) => {
    await login(page)
    await addToCart(page)
    await page.getByRole('button', { name: 'Adicionar Emerald Ape #042 aos favoritos', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Remover Emerald Ape #042 dos favoritos', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await logout(page)
    await login(page, 'bruno', '/profile')
    await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveValue('Bruno Orbit')
    await expect(page.getByLabel('E-mail', { exact: true })).toHaveValue(credentials.bruno)
    await expect(page.getByRole('main')).not.toContainText('Alice Cosmos')
    await page.goto('/wallets')
    await expect(page.locator('.account-wallet-card').getByRole('heading', { name: 'Carteira principal', exact: true })).toBeVisible()
    await expect(page.getByRole('heading', { name: 'Minha Ethereum', exact: true })).toHaveCount(0)
    await page.goto('/cart')
    await expect(page.getByText('O carrinho está vazio.', { exact: false })).toBeVisible()
    await page.goto('/nft/cosmic-001')
    await expect(page.getByRole('button', { name: 'Adicionar Emerald Ape #042 aos favoritos', exact: true })).toHaveAttribute('aria-pressed', 'false')
    await logout(page)
    await login(page)
    await page.goto('/cart')
    await expect(page.locator('.cart-line')).toHaveCount(1)
    await page.goto('/nft/cosmic-001')
    await expect(page.getByRole('button', { name: 'Remover Emerald Ape #042 dos favoritos', exact: true })).toHaveAttribute('aria-pressed', 'true')
    expect((await state(page)).orderCount).toBe(0)
  })
})

test.describe('04 · Favorito otimista e rollback', () => {
  test('exige sessão, reverte falha e persiste a recuperação', async ({ page }) => {
    await page.goto('/nft/cosmic-001')
    await page.getByRole('button', { name: 'Adicionar Emerald Ape #042 aos favoritos', exact: true }).click()
    await expect(page).toHaveURL(/\/login\?returnTo=%2Fnft%2Fcosmic-001/)
    await page.getByLabel('E-mail', { exact: true }).fill(credentials.alice)
    await page.getByLabel('Senha', { exact: true }).fill(credentials.password)
    await page.getByRole('button', { name: 'Entrar na conta', exact: true }).click()
    await expect(page).toHaveURL(/\/nft\/cosmic-001$/)
    const favorite = page.getByRole('button', { name: /^(Adicionar|Remover) Emerald Ape #042 (aos|dos) favoritos$/ })
    await expect(favorite).toHaveAttribute('aria-pressed', 'false')
    await demo(page, { scenario: 'favorite-error', latency: 600 })
    await favorite.click()
    await expect(favorite).toHaveAttribute('aria-pressed', 'true')
    await expect(page.locator('.notices')).toContainText(/favorit|salvar/i)
    await expect(favorite).toHaveAttribute('aria-pressed', 'false')
    await expect(favorite).toBeEnabled()
    await demo(page)
    await favorite.click()
    await expect(favorite).toHaveAttribute('aria-pressed', 'true')
    await expect(favorite).toBeEnabled()
    await page.reload()
    await expect(favorite).toHaveAttribute('aria-pressed', 'true')
    await favorite.click()
    await expect(favorite).toBeEnabled()
    await page.reload()
    await expect(favorite).toHaveAttribute('aria-pressed', 'false')
  })
})
